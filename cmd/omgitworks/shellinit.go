const powershellInitTemplate = `# omgitworks shell integration — do not edit, managed via shell-init
function omgw {
    if ($args.Count -eq 0) {
        & {BIN}
        return
    }

    $first = $args[0]
    $rest = @()
    if ($args.Count -gt 1) {
        $rest = $args[1..($args.Count - 1)]
    }

    switch -Regex ($first) {
        '^(list|init|add|refresh|print-workspace|tag|user|completion|shell-init|help|__.*)$' {
            & {BIN} @args
            return
        }
        '^worktree$' {
            if ($rest.Count -eq 0) {
                & {BIN} @args
                return
            }
            $second = $rest[0]
            switch ($second) {
                { $_ -in 'list', 'align', 'add', 'remove', 'rm' -or $_ -like '-*' } {
                    & {BIN} @args
                    return
                }
                # Help output goes to stdout; never capture it as a destination.
                { $rest -contains '-h' -or $rest -contains '--help' } {
                    & {BIN} @args
                    return
                }
                default {
                    $dest = & {BIN} @args -q 2>&1 | Where-Object { $_ -is [string] }
                    if ($dest) { Set-Location $dest }
                    return
                }
            }
        }
        '^cd$' {
            if ($rest.Count -gt 0) {
                & {BIN} @args
                return
            }
            $dest = & {BIN} cd -q 2>&1 | Where-Object { $_ -is [string] }
            if ($dest) { Set-Location $dest }
            return
        }
        '^(-p|--parent|parent)$' {
            $second = if ($rest.Count -gt 0) { $rest[0] } else { $null }
            $dest = & {BIN} parent $second -q 2>&1 | Where-Object { $_ -is [string] }
            if ($dest) { Set-Location $dest }
            return
        }
        '^-' {
            & {BIN} @args
            return
        }
        default {
            $second = if ($rest.Count -gt 0) { $rest[0] } else { $null }

            if ($second -eq '-p' -or $second -eq '--parent') {
                $dest = & {BIN} parent $first -q 2>&1 | Where-Object { $_ -is [string] }
                if ($dest) { Set-Location $dest }
                return
            }
            elseif ($second -eq '-wt') {
                if ($rest.Count -gt 1) {
                    $branch = $rest[1]
                    $dest = & {BIN} $first --worktree $branch -q 2>&1 | Where-Object { $_ -is [string] }
                } else {
                    $dest = & {BIN} $first --worktree -q 2>&1 | Where-Object { $_ -is [string] }
                }
                if ($dest) { Set-Location $dest }
                return
            }
            else {
                $dest = & {BIN} $first -q 2>&1 | Where-Object { $_ -is [string] }
                if ($dest) { Set-Location $dest }
                return
            }
        }
    }
}
# Compatibility: gws was the command before the rename to omgw.
function gws { omgw @args }
& {BIN} completion powershell | Invoke-Expression
(& {BIN} completion powershell) -replace 'omgitworks', 'omgw' | Invoke-Expression
(& {BIN} completion powershell) -replace 'omgitworks', 'gws' | Invoke-Expression
`

func runShellInit(_ *cobra.Command, args []string) error {
	script, err := renderShellInit(args[0], "omgitworks")
	if err != nil {
		return err
	}
	fmt.Print(script)
	return nil
}

// renderShellInit returns the shell integration for shell, invoking bin as the binary.
func renderShellInit(shell, bin string) (string, error) {
	var tmpl string
	switch shell {
	case "zsh":
		tmpl = zshInitTemplate
	case "bash":
		tmpl = bashInitTemplate
	case "powershell", "pwsh":
		tmpl = powershellInitTemplate
	default:
		return "", fmt.Errorf("unsupported shell %q (supported: zsh, bash, powershell)", shell)
	}
	return strings.ReplaceAll(tmpl, "{BIN}", bin), nil
}
