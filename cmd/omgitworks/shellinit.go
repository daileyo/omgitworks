var shellInitCmd = &cobra.Command{
	Use:   "shell-init [zsh|bash|powershell]",
	Short: "Output shell integration code to eval in your shell config",
	Long: `Outputs shell integration code for the given shell.

Add to the end of your ~/.zshrc or ~/.bashrc (after PATH is set):

  export PATH="$HOME/.local/bin:$PATH"
  eval "$(omgitworks shell-init zsh)"   # or: bash

For PowerShell, add to your $PROFILE:

  $env:Path = "$HOME\.local\bin;$env:Path"
  Invoke-Expression (& omgitworks shell-init powershell | Out-String)

This sets up the 'gws' shell function with tab completion. Because the
function is generated by the binary at shell startup, it always reflects
the current version of omgitworks — no manual updates needed.`,
	Args:      cobra.ExactArgs(1),
	ValidArgs: []string{"zsh", "bash", "powershell"},
	RunE:      runShellInit,
}

func init() {
	rootCmd.AddCommand(shellInitCmd)
}

const zshInitTemplate = `# omgitworks shell integration — do not edit, managed via shell-init
if ! type compdef &>/dev/null; then
  autoload -U compinit && compinit
fi
function omgw() {
  local _dest _arg
  if [[ $# -eq 0 ]]; then
    {BIN}
    return
  fi
  case "$1" in
    list|init|add|refresh|print-workspace|tag|user|completion|shell-init|help|__*) {BIN} "$@" ;;
    worktree)
      case "$2" in
        list|align|add|remove|rm|""|-*) {BIN} "$@" ;;
        *)
          # Help output goes to stdout; never capture it as a destination.
          for _arg in "${@:3}"; do
            case "$_arg" in
              -h|--help) {BIN} "$@"; return ;;
            esac
          done
          _dest="$({BIN} "$@" -q 2>/dev/tty </dev/tty)"
          [[ -n "$_dest" ]] && cd "$_dest"
          ;;
      esac
      ;;
    cd)
      if [[ -n "$2" ]]; then
        {BIN} "$@"
        return
      fi
      _dest="$({BIN} cd -q 2>/dev/tty </dev/tty)"
      [[ -n "$_dest" ]] && cd "$_dest"
      ;;
    -p|--parent|parent)
      _dest="$({BIN} parent "$2" -q 2>/dev/tty </dev/tty)"
      [[ -n "$_dest" ]] && cd "$_dest"
      ;;
    -*)
      {BIN} "$@"
      ;;
    *)
      if [[ "$2" == "-p" || "$2" == "--parent" ]]; then
        _dest="$({BIN} parent "$1" -q 2>/dev/tty </dev/tty)"
      elif [[ "$2" == "-wt" ]]; then
        if [[ -n "$3" ]]; then
          _dest="$({BIN} "$1" --worktree "$3" -q 2>/dev/tty </dev/tty)"
        else
          _dest="$({BIN} "$1" --worktree -q 2>/dev/tty </dev/tty)"
        fi
        [[ -n "$_dest" ]] && cd "$_dest"
        return
      else
        _dest="$({BIN} "$1" -q 2>/dev/tty </dev/tty)"
      fi
      [[ -n "$_dest" ]] && cd "$_dest"
      ;;
  esac
}
# Compatibility: gws was the command before the rename to omgw.
function gws() { omgw "$@"; }
source <({BIN} completion zsh)
compdef _omgitworks omgw
compdef _omgitworks gws
`

